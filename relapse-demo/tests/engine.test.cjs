assert.equal(E.analyze([...baseline,r(8000,8),r(8000,8)],opts).latest.score,0);
assert.equal(E.analyze([...baseline,r(1000,3),r(1000,3)],opts).latest.score,100);
assert.equal(E.analyze([...baseline,r(null,null),r(null,null)],opts).latest.status,'insufficient_data');
assert.equal(E.analyze([...baseline,r(0,0)],opts).latest.status,'collecting_window');
assert.equal(E.analyze([...baseline,r(1000,null),r(1000,null)],opts).latest.score,null);
assert.equal(E.analyze([...baseline,r(NaN,Infinity),r(NaN,Infinity)],opts).latest.score,null);
assert.equal(E.analyze([...baseline,r(15000,10),r(15000,10)],opts).latest.score,0);
